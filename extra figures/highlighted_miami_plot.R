
# ============================================================
# Example: Miami Plot with Highlighted csmGmm SNPs
# ============================================================
#
# This example generates a Miami plot highlighting SNPs
# identified as replicated by csmGmm.
#
# Dataset 1: African females (GCST90551892)
# Dataset 2: European females (iCOGS, GCST010098)
#
# Both datasets use genome build 37.
#
# The replication analysis must be completed before running
# this script.
#
# ============================================================


# 1. Load required packages
# ------------------------------------------------------------

library(readr)
library(dplyr)
library(ggplot2)
library(cowplot)


# 2. Read GWAS summary statistics
# ------------------------------------------------------------

iCOGS <- read_tsv(
  "data/GCST010098.tsv",
  col_select = c(
    variant_id,
    chromosome,
    base_pair_location,
    beta,
    standard_error,
    effect_allele,
    other_allele,
    p_value
  ),
  progress = FALSE
)

Africa <- read_tsv(
  "data/GCST90551892.tsv.gz",
  col_select = c(
    variant_id,
    chromosome,
    base_pair_location,
    beta,
    standard_error,
    effect_allele,
    other_allele,
    p_value
  ),
  progress = FALSE
)


# 3. Read significant csmGmm SNPs
# ------------------------------------------------------------
#
# This file is generated by example_replication_analysis.R.

sig_snps <- read_csv(
  "results/csmgmm_rep_results.csv",
  show_col_types = FALSE
)

highlight_snps <- sig_snps %>%
  select(Chr, BP) %>%
  distinct()


# 4. Prepare African GWAS data
# ------------------------------------------------------------

Africa_miami <- Africa %>%
  transmute(
    Chr = as.integer(chromosome),
    BP = base_pair_location,
    logp = -log10(p_value)
  ) %>%
  filter(
    !is.na(Chr),
    Chr >= 1,
    Chr <= 22,
    !is.na(BP),
    is.finite(logp)
  ) %>%
  left_join(
    highlight_snps %>% mutate(highlight = TRUE),
    by = c("Chr", "BP")
  ) %>%
  mutate(
    highlight = ifelse(is.na(highlight), FALSE, highlight)
  )

rm(Africa)


# 5. Prepare iCOGS GWAS data
# ------------------------------------------------------------

iCOGS_miami <- iCOGS %>%
  transmute(
    Chr = as.integer(chromosome),
    BP = base_pair_location,
    logp = -log10(p_value)
  ) %>%
  filter(
    !is.na(Chr),
    Chr >= 1,
    Chr <= 22,
    !is.na(BP),
    is.finite(logp)
  ) %>%
  left_join(
    highlight_snps %>% mutate(highlight = TRUE),
    by = c("Chr", "BP")
  ) %>%
  mutate(
    highlight = ifelse(is.na(highlight), FALSE, highlight)
  )

rm(iCOGS)


# 6. Calculate chromosome offsets
# ------------------------------------------------------------

chr_table <- bind_rows(
  Africa_miami %>% select(Chr, BP),
  iCOGS_miami %>% select(Chr, BP)
) %>%
  group_by(Chr) %>%
  summarise(
    chrLength = max(BP, na.rm = TRUE),
    .groups = "drop"
  ) %>%
  arrange(Chr)

chrOffsets <- cumsum(chr_table$chrLength)
names(chrOffsets) <- chr_table$Chr


# 7. Calculate cumulative genomic positions
# ------------------------------------------------------------

add_true_pos <- function(df, chrOffsets) {
  df %>%
    arrange(Chr, BP) %>%
    mutate(
      truePos = BP + ifelse(
        Chr == 1,
        0,
        chrOffsets[as.character(Chr - 1)]
      )
    )
}

Africa_miami <- add_true_pos(Africa_miami, chrOffsets)
iCOGS_miami <- add_true_pos(iCOGS_miami, chrOffsets)


# 8. Define chromosome axis labels
# ------------------------------------------------------------

xBreaks <- chrOffsets[as.character(1:22)]

xBreaksLabs <- ifelse(
  (1:22) %% 2 == 0,
  "",
  as.character(1:22)
)


# 9. Generate Miami plot
# ------------------------------------------------------------

miami_plot <- ggplot() +

  # Top: European ancestry (iCOGS)
  geom_point(
    data = iCOGS_miami,
    aes(x = truePos, y = logp),
    color = ifelse(
      iCOGS_miami$Chr %% 2 == 0,
      "grey70",
      "blue"
    ),
    alpha = 0.5,
    size = 0.7
  ) +

  # Highlight csmGmm replicated SNPs
  geom_point(
    data = iCOGS_miami %>% filter(highlight),
    aes(x = truePos, y = logp),
    color = "#D4A72C",
    size = 2.0
  ) +

  # Bottom: South African
  geom_point(
    data = Africa_miami,
    aes(x = truePos, y = -logp),
    color = ifelse(
      Africa_miami$Chr %% 2 == 0,
      "grey70",
      "red"
    ),
    alpha = 0.5,
    size = 0.7
  ) +

  # Highlight csmGmm replicated SNPs
  geom_point(
    data = Africa_miami %>% filter(highlight),
    aes(x = truePos, y = -logp),
    color = "#D4A72C",
    size = 2.0
  ) +

  # Legend
  geom_point(
    aes(x = NA, y = NA, color = "European ancestry"),
    size = 2
  ) +

  geom_point(
    aes(x = NA, y = NA, color = "South African"),
    size = 2
  ) +

  geom_point(
    aes(x = NA, y = NA, color = "csmGmm replicated SNPs"),
    size = 3
  ) +

  scale_color_manual(
    name = NULL,
    values = c(
      "European ancestry" = "blue",
      "South African" = "red",
      "csmGmm replicated SNPs" = "#D4A72C"
    ),
    breaks = c(
      "European ancestry",
      "South African",
      "csmGmm replicated SNPs"
    )
  ) +

  scale_x_continuous(
    name = "Chromosome",
    breaks = xBreaks,
    labels = xBreaksLabs
  ) +

  scale_y_continuous(
    name = "-log10(p-value)",
    limits = c(-30, 120),
    breaks = seq(-30, 120, 10)
  ) +

  theme_cowplot() +

  theme(
    axis.text = element_text(size = 20),
    axis.title = element_text(size = 21),
    legend.position = "right",
    legend.text = element_text(size = 21),
    legend.key.height = unit(0.8, "cm")
  )


# 10. Display plot
# ------------------------------------------------------------

print(miami_plot)


# 11. Save Miami plot
# ------------------------------------------------------------

if (!dir.exists("results")) {
  dir.create("results")
}

ggsave(
  filename = "results/miami_plot_highlighted_new.png",
  plot = miami_plot,
  width = 14,
  height = 6,
  dpi = 300
)


